print("-----------------------------------------")

fruits = ["apple", "banana", "cherry", "mango"]
vegetables = ['Tomoto','Potato','Cabbage','Onion','Carrot']
animal_products = ['milk','meat','butter','yoghurt']
web_techs = ['HTML','CSS',"JS",'React','Redux','Node','MangoDB']
countries = ['Finland','England', 'Australia', 'Germany','Italy' ]

print("Fruits: ", fruits)
print("Number of Furits {}".format(len(fruits)))
